import { describe, it, expect } from 'vitest';
import type { ParameterInfo, TableInfo } from '../types';
import { getSqlDialect, mssqlDialect, postgresDialect, SQL_MONACO_LANGUAGES } from '.';
import { splitPostgresStatements } from '../utils/sql/splitPostgres';
import {
  parseTableAliases,
  getCompletionContext,
  extractReferencedTables,
  extractUpdateTableName,
} from '../utils/sqlAstExtractor';
import { extractAllStatements, extractStatementAtCursor } from '../utils/queryExtractor';
import { SqlValidator } from '../utils/sqlValidator';

const param = (name: string, mode = 'IN'): ParameterInfo => ({
  name,
  data_type: 'integer',
  max_length: null,
  precision: null,
  scale: null,
  parameter_mode: mode,
  ordinal_position: 1,
  has_default: false,
});

const table: TableInfo = {
  schema_name: 'public',
  table_name: 'users',
  table_type: 'BASE TABLE',
  columns: [
    { name: 'id', data_type: 'integer', max_length: null, precision: null, scale: null, is_nullable: false, is_primary_key: true, is_identity: true, is_computed: false, column_default: null, ordinal_position: 1 },
    { name: 'Email', data_type: 'text', max_length: null, precision: null, scale: null, is_nullable: true, is_primary_key: false, is_identity: false, is_computed: false, column_default: "''::text", ordinal_position: 2 },
  ],
};

describe('getSqlDialect', () => {
  it('maps SQL drivers to dialects and MongoDB to none', () => {
    expect(getSqlDialect('mssql')).toBe(mssqlDialect);
    expect(getSqlDialect('postgres')).toBe(postgresDialect);
    expect(getSqlDialect('mongodb')).toBeNull();
    expect(SQL_MONACO_LANGUAGES).toEqual(['sql', 'pgsql']);
  });
});

describe('dialect vocabulary', () => {
  it('offers engine-specific keywords and functions', () => {
    expect(postgresDialect.keywords).toEqual(expect.arrayContaining(['LIMIT', 'ILIKE', 'RETURNING', 'ON CONFLICT']));
    expect(postgresDialect.keywords).not.toContain('TOP');
    expect(postgresDialect.functions).toEqual(expect.arrayContaining(['NOW', 'DATE_TRUNC', 'GENERATE_SERIES']));
    expect(postgresDialect.functions).not.toContain('GETDATE');
    expect(mssqlDialect.keywords).toEqual(expect.arrayContaining(['TOP', 'CROSS APPLY']));
    expect(mssqlDialect.keywords).not.toContain('LIMIT');
  });
});

describe('query builders', () => {
  it('builds top-N queries per dialect', () => {
    expect(mssqlDialect.selectTopQuery('dbo', 'Users', 100)).toBe('SELECT TOP 100 * FROM [dbo].[Users]');
    expect(postgresDialect.selectTopQuery('public', 'users', 100)).toBe('SELECT * FROM public.users LIMIT 100');
    expect(postgresDialect.selectTopQuery('Sales', 'Order', 5)).toBe('SELECT * FROM "Sales"."Order" LIMIT 5');
  });

  it('builds routine calls per dialect', () => {
    expect(mssqlDialect.procedureCallSnippet('dbo', 'usp_Get', [param('@id'), param('@out', 'OUT')]))
      .toBe('usp_Get @id = ${1:NULL}');
    expect(mssqlDialect.functionCallSnippet('dbo', 'fn', [param('@a')])).toBe('[dbo].[fn](${1:NULL})');
    expect(postgresDialect.procedureCallSnippet('public', 'archive', [param('a'), param('b')]))
      .toBe('archive(${1:NULL}, ${2:NULL})');
    expect(postgresDialect.functionCallSnippet('util', 'now_utc', [])).toBe('util.now_utc()');
  });

  it('synthesizes CREATE TABLE scripts per dialect', () => {
    const pg = postgresDialect.createTableScript(table);
    expect(pg).toContain('CREATE TABLE public.users (');
    expect(pg).toContain('id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(pg).toContain('"Email" text DEFAULT');
    expect(pg).toContain('PRIMARY KEY (id)');
    const ms = mssqlDialect.createTableScript({ ...table, schema_name: 'dbo' });
    expect(ms).toContain('CREATE TABLE [dbo].[users] (');
    expect(ms).toContain('[id] integer IDENTITY(1,1) NOT NULL');
  });

  it('reads definitions from the engine catalog', () => {
    expect(mssqlDialect.objectDefinitionQuery('view', 'dbo', 'v')).toContain('OBJECT_DEFINITION');
    expect(postgresDialect.objectDefinitionQuery('view', 'public', 'v')).toContain('pg_get_viewdef');
    const fn = postgresDialect.objectDefinitionQuery('routine', 'public', "o'brien");
    expect(fn).toContain('pg_get_functiondef');
    expect(fn).toContain("p.proname = 'o''brien'");
  });
});

describe('splitPostgresStatements', () => {
  it('keeps dollar-quoted bodies, E-strings and nested comments intact', () => {
    const sql = [
      "CREATE FUNCTION f() RETURNS int AS $$ BEGIN RETURN 1; END; $$ LANGUAGE plpgsql;",
      "SELECT E'it\\'s; ok', 'x;y' /* a /* ; */ b */;",
      'SELECT "semi;colon" FROM t',
    ].join('\n');
    expect(splitPostgresStatements(sql)).toEqual([
      'CREATE FUNCTION f() RETURNS int AS $$ BEGIN RETURN 1; END; $$ LANGUAGE plpgsql',
      "SELECT E'it\\'s; ok', 'x;y' /* a /* ; */ b */",
      'SELECT "semi;colon" FROM t',
    ]);
  });

  it('treats $1 placeholders and identifier dollars as code', () => {
    expect(splitPostgresStatements('SELECT $1; SELECT a$b$ FROM t;')).toEqual(['SELECT $1', 'SELECT a$b$ FROM t']);
  });

  it('drops comment-only fragments', () => {
    expect(splitPostgresStatements('SELECT 1; -- trailing note')).toEqual(['SELECT 1']);
  });
});

describe('sqlAstExtractor with the PostgreSQL dialect', () => {
  it('resolves unqualified tables to public, not dbo', () => {
    const aliases = parseTableAliases('SELECT u.id FROM users u JOIN orders o ON o.user_id = u.id', postgresDialect);
    expect(aliases.get('u')).toEqual({ schema: 'public', table: 'users' });
    expect(aliases.get('o')).toEqual({ schema: 'public', table: 'orders' });
    // SQL Server keeps dbo
    expect(parseTableAliases('SELECT u.Id FROM Users u', mssqlDialect).get('u')).toEqual({ schema: 'dbo', table: 'Users' });
  });

  it('parses PostgreSQL-only syntax', () => {
    const tables = extractReferencedTables('SELECT id::text FROM sales.orders WHERE note ILIKE \'%x%\' LIMIT 5', postgresDialect);
    expect(tables).toEqual([{ schema: 'sales', table: 'orders' }]);
    expect(extractUpdateTableName('UPDATE users SET name = 1 RETURNING id', postgresDialect))
      .toEqual({ schema: 'public', table: 'users' });
  });

  it('uses the dialect for completion context', () => {
    expect(getCompletionContext('CALL ', 'CALL ', postgresDialect).type).toBe('routine');
    expect(getCompletionContext('EXEC ', 'EXEC ', mssqlDialect).type).toBe('routine');
    expect(getCompletionContext('SELECT * FROM public.', 'SELECT * FROM public.', postgresDialect).type).toBe('schema');
    expect(getCompletionContext('USE ', 'USE ', postgresDialect).type).not.toBe('database');
    expect(getCompletionContext('USE ', 'USE ', mssqlDialect).type).toBe('database');
    expect(getCompletionContext('TRUNCATE ', 'TRUNCATE ', postgresDialect).type).toBe('table');
  });
});

describe('queryExtractor with the PostgreSQL dialect', () => {
  const script = [
    'CREATE FUNCTION f() RETURNS int AS $$',
    'BEGIN',
    '  RETURN 1;',
    'END;',
    '$$ LANGUAGE plpgsql;',
    '',
    'SELECT 1;',
  ].join('\n');

  it('keeps function bodies in one statement', () => {
    const statements = extractAllStatements(script, postgresDialect);
    expect(statements).toHaveLength(2);
    expect(statements[0].startLine).toBe(1);
    expect(statements[1].startLine).toBe(7);
  });

  it('runs the whole function when the cursor is inside its body', () => {
    const location = extractStatementAtCursor(script, 3, 5, postgresDialect);
    expect(location?.statement).toContain('$$ LANGUAGE plpgsql');
    expect(location?.statement.startsWith('CREATE FUNCTION')).toBe(true);
  });

  it('does not treat GO as a batch separator', () => {
    const statements = extractAllStatements('SELECT 1\nGO\nSELECT 2', postgresDialect);
    expect(statements).toHaveLength(1);
  });
});

describe('SqlValidator with the PostgreSQL dialect', () => {
  it('accepts PostgreSQL syntax', () => {
    const validator = new SqlValidator();
    const errors = validator.validateQuery("SELECT id::text FROM users WHERE name ILIKE 'a%' LIMIT 10", null, postgresDialect);
    expect(errors).toEqual([]);
  });
});
